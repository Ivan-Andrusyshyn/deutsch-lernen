const ukrainianTermLookup = Object.fromEntries(
  Object.entries(ukrainianTerms).map(([source, target]) => [source.toLocaleLowerCase('ru'), target]),
);
const ukrainianTermPattern = new RegExp(
  `(^|[^\\p{L}])(${Object.keys(ukrainianTerms)
    .sort((left, right) => right.length - left.length)
    .map((term) => term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('|')})(?=$|[^\\p{L}])`,
  'giu',
);

function toUkrainian(value: string): string {
  if (categoryTranslations[value]) return categoryTranslations[value];

  return value.replace(ukrainianTermPattern, (_match, prefix: string, source: string) => {
    const target = ukrainianTermLookup[source.toLocaleLowerCase('ru')];
    const startsWithUppercase = source[0] === source[0].toLocaleUpperCase('ru');
    return `${prefix}${startsWithUppercase ? target[0].toLocaleUpperCase('uk') + target.slice(1) : target}`;
  });
}

